/**
 * Generates src/lib/logo.generated.ts from Gully Chain kit v4's gc-icon.svg (apps/web/public/identity).
 *
 *   GC_ICON_SVG_B64   the file itself, byte-identical. test/logo.test.ts holds it to the kit's hash.
 *   ICON_PNG          that file rendered, for terminals with an image protocol: none of them draws SVG.
 *   MARK              that file rendered as pixel rows, for coloured half-blocks everywhere else.
 *
 * Both renderings are of the file, never a redraw or a recolour. Needs sharp, which is not a dependency of
 * this package: GEN_LOGO_TOOLS=/path/to/a/folder-with-sharp/x.js node scripts/gen-logo.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(process.env.GEN_LOGO_TOOLS ?? import.meta.url);
const sharp = require("sharp");

const ICON = join(here, "..", "..", "..", "apps", "web", "public", "identity", "gc-icon.svg");
const OUT = join(here, "..", "src", "lib", "logo.generated.ts");
const ICON_PX = 240;
const MARK_COLS = 16;

const svg = readFileSync(ICON);
const png = await sharp(svg, { density: 300 }).resize(ICON_PX, ICON_PX).png({ compressionLevel: 9 }).toBuffer();
const { data } = await sharp(svg, { density: 300 }).resize(MARK_COLS, MARK_COLS, { kernel: "lanczos3" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });

const rows = [];
for (let y = 0; y < MARK_COLS; y++) {
  const cells = [];
  for (let x = 0; x < MARK_COLS; x++) {
    const i = (y * MARK_COLS + x) * 4;
    const hex = [data[i], data[i + 1], data[i + 2]].map((v) => v.toString(16).padStart(2, "0")).join("");
    cells.push(data[i + 3] < 110 ? "" : hex);
  }
  rows.push(cells.join(","));
}

writeFileSync(
  OUT,
  [
    "// SPDX-License-Identifier: MIT",
    "// GENERATED by scripts/gen-logo.mjs from kit v4's gc-icon.svg. Do not edit by hand.",
    "",
    "/** The kit's gc-icon.svg, byte-identical. */",
    `export const GC_ICON_SVG_B64 = "${svg.toString("base64")}";`,
    "",
    "/** That file rendered to PNG: no terminal image protocol draws SVG. */",
    `export const ICON_PNG = "${png.toString("base64")}";`,
    "",
    "/** That file rendered, one string per pixel row: comma-separated 6-hex colours, empty = transparent. */",
    `export const MARK: readonly string[] = ${JSON.stringify(rows)};`,
    "",
  ].join("\n"),
);
console.log(`gen-logo: wrote ${OUT} (svg ${svg.length} bytes, png ${png.length} bytes)`);
